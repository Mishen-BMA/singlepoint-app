require('dotenv').config();
const fs = require('fs');
const path = require('path');

const databaseUrl = process.env.DATABASE_URL || 'sqlite:./data/singlepoint.sqlite';

if (databaseUrl.startsWith('sqlite:')) {
  const Database = require('better-sqlite3');
  const configuredPath = databaseUrl.slice('sqlite:'.length);
  const filename = configuredPath === ':memory:'
    ? configuredPath
    : path.resolve(process.cwd(), configuredPath || './data/singlepoint.sqlite');

  if (filename !== ':memory:') {
    fs.mkdirSync(path.dirname(filename), { recursive: true });
  }

  const connection = new Database(filename);
  connection.pragma('foreign_keys = ON');

  const sqliteDb = {
    dialect: 'sqlite',
    async query(sql, parameters = []) {
      const sqliteParameters = [];
      const sqliteSql = sql
        .replace(/BIGINT\s+GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/gi, 'INTEGER PRIMARY KEY AUTOINCREMENT')
        .replace(/TIMESTAMPTZ/gi, 'TEXT')
        .replace(/::(?:jsonb|int)\b/gi, '')
        .replace(/JSONB/gi, 'TEXT')
        .replace(/NOW\(\)/gi, 'CURRENT_TIMESTAMP')
        .replace(/\$(\d+)/g, (_, position) => {
          const value = parameters[Number(position) - 1];
          sqliteParameters.push(typeof value === 'boolean' ? Number(value) : value);
          return '?';
        });
      const statement = connection.prepare(sqliteSql);
      if (statement.reader) {
        const rows = statement.all(...sqliteParameters);
        return { rows, rowCount: rows.length };
      }
      const result = statement.run(...sqliteParameters);
      return { rows: [], rowCount: result.changes };
    },
    async end() {
      connection.close();
    },
    // better-sqlite3 uses a single connection, so BEGIN/COMMIT issued through
    // the shared query() function are already transactional (statements are
    // serialized on the same connection). The callback receives sqliteDb.query
    // so migrations/model code can use one function regardless of dialect.
    async transaction(callback) {
      await sqliteDb.query('BEGIN');
      try {
        const result = await callback(sqliteDb.query);
        await sqliteDb.query('COMMIT');
        return result;
      } catch (error) {
        try { await sqliteDb.query('ROLLBACK'); } catch (_rollbackError) { /* ignore */ }
        throw error;
      }
    }
  };

  module.exports = sqliteDb;
} else if (databaseUrl.startsWith('postgres://') || databaseUrl.startsWith('postgresql://')) {
  const { Pool } = require('pg');
  const pool = new Pool({
    connectionString: databaseUrl,
    ssl: process.env.PGSSLMODE === 'require' ? { rejectUnauthorized: false } : undefined
  });

  pool.on('error', (error) => {
    console.error('Unexpected PostgreSQL pool error:', error.message);
  });

  pool.dialect = 'postgres';
  // pool.query() may hand out a different connection per call, so raw
  // BEGIN/COMMIT via pool.query() is NOT transactional. Checkout a single
  // client and run the whole callback against it instead.
  pool.transaction = async function transaction(callback) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await callback(client.query.bind(client));
      await client.query('COMMIT');
      return result;
    } catch (error) {
      try { await client.query('ROLLBACK'); } catch (_rollbackError) { /* ignore */ }
      throw error;
    } finally {
      client.release();
    }
  };
  module.exports = pool;
} else {
  throw new Error('DATABASE_URL must use sqlite:, postgres://, or postgresql://');
}